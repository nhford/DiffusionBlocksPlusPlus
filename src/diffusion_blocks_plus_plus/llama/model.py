class AdaRMS(nn.Module):
    """
    RMSNorm equivalent to the AdaLN normalization from Peebles and Xie (https://arxiv.org/abs/2212.09748).

    In detail, this layer takes an embedding and a conditioning tensor, whose
    dimensions must be breadcastable except for the last dimension, computes a
    bias and scale for each channel, and then applies RMSNorm on the embeddings
    using the computed bias and scale.
    """

    def __init__(
        self, cond_size: int, features: int, eps: float, bias=True, hidden_bias=True
    ):
        """Initializes an AdaRMS Module.

        Args:
            cond_size: The size of the conditioning vector
            features: The size of the embeddings being normalized by this layer.
            bias: Whether this layer applies embeddings to the normalized
            embeddings.
        """
        super().__init__()
        self.silu = nn.SiLU()
        self.bias = bias
        self.eps = eps
        if bias:
            self.linear = nn.Linear(cond_size, features * 2, bias=hidden_bias)
        else:
            self.linear = nn.Linear(cond_size, features, bias=hidden_bias)

    def forward(self, embeddings: torch.Tensor, conditioning: torch.Tensor):
        rmsnorm_params: torch.Tensor = self.silu(self.linear(conditioning))
        if self.bias:
            scale, bias = rmsnorm_params.chunk(2, -1)
        else:
            scale = rmsnorm_params
            bias = torch.zeros_like(scale)

        scale += 1

        return (
            embeddings / (embeddings.norm(p=2, dim=-1, keepdim=True) + self.eps) * scale
            + bias
        )


class TimestepEmbedder(nn.Module):
    """
    This module computes timestep embeddings by running a frequency embedding
    through a MLP.

    This module takes a timestep in the range 0-1 for each batch (tensor of
    shape [batch_size]), and returns a batch of embeddings
    [batch_size, hidden_size].
    """

    def __init__(self, hidden_size, frequency_embedding_size=256):
        super().__init__()
        self.mlp = nn.Sequential(
            nn.Linear(frequency_embedding_size, hidden_size),
            nn.SiLU(),
            nn.Linear(hidden_size, hidden_size),
        )
        self.frequency_embedding_size = frequency_embedding_size

    @staticmethod
    def timestep_embedding(t, dim, max_frequency=10000):
        # Note: We modify Sakana.ai's implementation of the code here to use a
        # large maximum frequency instead of a period.
        # This should make the timestep embedding more informative.
        half = dim // 2
        freqs = torch.exp(
            math.log(max_frequency) * torch.arange(start=0, end=half) / half
        ).to(t.device)
        args = t[:, None] * freqs[None]
        embedding = torch.cat([torch.cos(args), torch.sin(args)], dim=-1)
        if dim % 2:
            embedding = torch.cat(
                [embedding, torch.zeros_like(embedding[:, :1])], dim=-1
            )
        return embedding

    def forward(self, t):
        t_freq = self.timestep_embedding(t, self.frequency_embedding_size).to(
            dtype=next(self.parameters()).dtype
        )
        t_emb = self.mlp(t_freq)
        return t_emb


